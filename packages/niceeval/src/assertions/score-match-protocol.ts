import * as Predicate from "effect/Predicate";
import * as Schema from "effect/Schema";
import { unitSchema } from "./score-match-schemas.ts";

export const probabilityTolerance = 1e-6;
const typesafeRationalePrefix = "TypeSafe result summary (generated by NiceEval):";
const isUnit = Schema.is(unitSchema);
export const typeSafeUsageSchema = Schema.Struct({
  input_tokens: Schema.Int.check(Schema.isGreaterThanOrEqualTo(0)),
  output_tokens: Schema.Int.check(Schema.isGreaterThanOrEqualTo(0)),
});

export function finiteUnit(value: unknown, label: string): number {
  if (!isUnit(value)) throw new TypeError(`${label} must be finite in [0, 1]`);
  return value;
}

/** Validates a JSON object's exact fields, preserving gateway error boundaries. */
export function exactProtocolObject(value: unknown, keys: readonly string[], label: string): Record<string, unknown> {
  if (!Predicate.isObject(value)) throw new TypeError("Expected an object");
  const actual = Object.keys(value).sort();
  const expected = [...keys].sort();
  if (actual.length !== expected.length || actual.some((key, index) => key !== expected[index]))
    throw new TypeError(`${label} has an invalid shape`);
  return value;
}

/** Normalizes in declared label order; the reader first captures data properties. */
export function typeSafeProbabilities(value: unknown, labels: readonly string[]): Readonly<Record<string, number>> {
  const input = exactProtocolObject(value, labels, "TypeSafe probabilities");
  const entries = labels.map((label) => [label, finiteUnit(input[label], `Probability ${label}`)] as const);
  const total = entries.reduce((sum, [, probability]) => sum + probability, 0);
  if (Math.abs(total - 1) > probabilityTolerance || total === 0)
    throw new TypeError("TypeSafe probabilities must sum to 1");
  return Object.freeze(Object.fromEntries(entries.map(([label, probability]) => [label, probability / total])));
}

export function typeSafeScoreProjection(
  anchors: readonly { readonly measurement: number }[],
  labels: readonly string[],
  distribution: Readonly<Record<string, number>>,
): { readonly measurement: number; readonly rationale: string } {
  const measurement = labels.reduce((sum, label, index) => sum + anchors[index]!.measurement * distribution[label]!, 0);
  return {
    measurement,
    rationale: `${typesafeRationalePrefix} probability-weighted ${labels.length}-level measurement ${measurement}.`,
  };
}

export function typeSafeChoiceProjection(choice: string): { readonly choice: string; readonly rationale: string } {
  return Object.freeze({
    choice,
    rationale: `${typesafeRationalePrefix} selected ${JSON.stringify(choice)} from the returned probability distribution.`,
  });
}
