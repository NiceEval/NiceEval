export type TranslationKey = keyof typeof resources.en.translation;

const storedLanguage = (): "en" | "zh-CN" => {
  try {
    const value = localStorage.getItem("niceeval-view-language");
    if (value === "en" || value === "zh-CN") return value;
  } catch {
    // Storage is optional; browser preference remains a safe fallback.
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
};

void i18n.use(initReactI18next).init({
  resources,
  lng: storedLanguage(),
  fallbackLng: "en",
  supportedLngs: ["en", "zh-CN"],
  interpolation: { escapeValue: false },
  returnNull: false,
});

i18n.on("languageChanged", (language) => {
  document.documentElement.lang = language;
  try { localStorage.setItem("niceeval-view-language", language); } catch { /* optional */ }
});

document.documentElement.lang = i18n.resolvedLanguage ?? "en";

export default i18n;
